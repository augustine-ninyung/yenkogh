/** Festivals celebrated in a region, including those shared with other regions. */
export const getFestivalsByRegion = (region: string): Festival[] =>
  festivals.filter((f) => f.region === region || f.otherRegions.includes(region));

export const getFestivalById = (id: string): Festival | undefined =>
  festivals.find((f) => f.id === id);

export const MONTH_NAMES = [
  'January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December',
];

/**
 * Calendar months (0 = January) in which a festival usually falls, read from its
 * `month` text. Ranges are expanded and may wrap the year ("November – January").
 * Returns an empty list for festivals with no fixed month: lunar-calendar
 * festivals, ones that recur through the year, and ones with no month on record.
 */
export const getFestivalMonths = (f: Festival): number[] => {
  const months = new Set<number>();
  for (const segment of f.month.split(/\band\b|,/)) {
    const found = MONTH_NAMES.map((name, index) => ({ index, at: segment.indexOf(name) }))
      .filter((m) => m.at >= 0)
      .sort((a, b) => a.at - b.at)
      .map((m) => m.index);
    if (found.length === 2 && segment.includes('–')) {
      for (let m = found[0]; ; m = (m + 1) % 12) {
        months.add(m);
        if (m === found[1]) break;
      }
    } else {
      found.forEach((m) => months.add(m));
    }
  }
  return [...months];
};
