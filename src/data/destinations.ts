export const getFeaturedDestinations = (): Destination[] =>
  destinations.filter((d) => d.featured);

export const getDestinationById = (id: string): Destination | undefined =>
  destinations.find((d) => d.id === id);

export const getDestinationsByRegion = (regionCode: string): Destination[] =>
  destinations.filter((d) => d.regionCode === regionCode);

export const getDestinationBySlug = (slug: string): Destination | undefined =>
  destinations.find((d) => d.slug === slug);

export const searchDestinations = (query: string): Destination[] => {
  const q = query.toLowerCase();
  return destinations.filter(
    (d) =>
      d.name.toLowerCase().includes(q) ||
      d.description.toLowerCase().includes(q) ||
      d.tags.some((t) => t.toLowerCase().includes(q)) ||
      d.region.toLowerCase().includes(q),
  );
};
